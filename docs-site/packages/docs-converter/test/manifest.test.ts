import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseNav, parseSection, navToSidebar, sidebarToNav } from '../src/manifest.js';
import { ConfigError } from '../src/config.js';
import { tempSource } from './helpers.js';

const docs = 'site/docs';
const repo = () => tempSource({
  'site/docs/overview.mdx': '---\ntitle: Gateway overview\n---\n\n# Gateway overview\n',
  'site/docs/setup/index.md': '# Setup\n',
  'site/docs/setup/configure.mdx': '---\nid: configuration\ntitle: Configure\n---\n',
});

test('a navigation of pages, categories and https links is accepted', () => {
  const nav = parseNav([
    { page: 'site/docs/overview.mdx', label: 'Overview' },
    { category: 'Setup', collapsed: false, overview: 'site/docs/setup/index.md', items: [{ page: 'site/docs/setup/configure.mdx' }] },
    { link: 'https://example.com/api', label: 'API reference' },
  ]);
  assert.equal(nav.length, 3);
});

test('a navigation with code-like or unknown entries is rejected', () => {
  const bad: unknown[] = [
    [{ page: '../outside.md' }],
    [{ page: '/abs.md' }],
    [{ link: 'http://example.com', label: 'Plain http' }],
    [{ link: 'javascript:alert(1)', label: 'x' }],
    [{ category: '', items: [] }],
    [{ category: 'Setup' }],
    [{ page: 'a.md', type: 'autogenerated' }],
    [{ autogenerated: 'site/docs' }],
    'not a list',
  ];
  for (const raw of bad) assert.throws(() => parseNav(raw), ConfigError, JSON.stringify(raw));
});

test('a section names its id, version and release tag prefix', () => {
  assert.deepEqual(parseSection({ id: 'api-platform-api-gateway', label: 'API Gateway', version: '1.2.0', release_tag: 'gateway/v' }),
    { id: 'api-platform-api-gateway', label: 'API Gateway', version: '1.2.0', release_tag: 'gateway/v' });
  assert.equal(parseSection({ id: 'hub', version: 'latest', release_tag: 'v' }).version, 'latest');
  for (const raw of [
    { id: 'Bad Id', version: '1.2.0', release_tag: 'v' },
    { id: 'x', version: '1.2', release_tag: 'v' },
    { id: 'x', version: '1.2.0.1', release_tag: 'v' },
    { id: 'x', version: '1.2.0', release_tag: 'portals/ai-workspace/v' },
    { id: 'x', version: '1.2.0', release_tag: 'gateway/' },
    { id: 'x', version: '1.2.0', release_tag: 'v', include: ['../shared'] },
  ]) assert.throws(() => parseSection(raw), ConfigError, JSON.stringify(raw));
});

test('navigation becomes Docusaurus sidebar items, using front matter ids and keeping labels', () => {
  const root = repo();
  const nav = parseNav([
    { page: 'site/docs/overview.mdx', label: 'Overview' },
    { category: 'Setup', collapsed: true, overview: 'site/docs/setup/index.md', items: [{ page: 'site/docs/setup/configure.mdx' }] },
    { link: 'https://example.com/api', label: 'API reference' },
  ]);
  const { items, missing } = navToSidebar(nav, root, docs);
  assert.deepEqual(missing, []);
  assert.deepEqual(items, [
    { type: 'doc', id: 'overview', label: 'Overview' },
    { type: 'category', label: 'Setup', collapsed: true, link: { type: 'doc', id: 'setup/index' }, items: [{ type: 'doc', id: 'setup/configuration' }] },
    { type: 'link', href: 'https://example.com/api', label: 'API reference' },
  ]);
});

test('navigation pages that do not exist or sit outside the docs folder are reported', () => {
  const root = repo();
  const { items, missing } = navToSidebar(parseNav([{ page: 'site/docs/gone.md' }, { page: 'site/other.md' }, { page: 'site/docs/overview.mdx' }]), root, docs);
  assert.deepEqual(missing, ['site/docs/gone.md', 'site/other.md']);
  assert.deepEqual(items, [{ type: 'doc', id: 'overview' }]);
});

test('a Docusaurus sidebar becomes a navigation with repo-relative page paths, keeping labels', () => {
  const root = repo();
  const { nav, problems } = sidebarToNav([
    'overview',
    { type: 'category', label: 'Setup', link: { type: 'doc', id: 'setup/index' }, items: [{ type: 'doc', id: 'setup/configuration', label: 'Configure it' }] },
    { type: 'link', href: 'https://example.com/api', label: 'API reference' },
    { type: 'autogenerated', dirName: 'setup' },
    { type: 'doc', id: 'missing/page' },
  ], root, docs);
  assert.deepEqual(nav, [
    { page: 'site/docs/overview.mdx' },
    { category: 'Setup', overview: 'site/docs/setup/index.md', items: [{ page: 'site/docs/setup/configure.mdx', label: 'Configure it' }] },
    { link: 'https://example.com/api', label: 'API reference' },
  ]);
  assert.deepEqual(problems, ['autogenerated items are not supported (dirName setup)', 'no page for doc id missing/page']);
});

test('the published JSON Schema allows exactly the keys the validator accepts', async () => {
  const fs = await import('node:fs');
  const schema = JSON.parse(fs.readFileSync(new URL('../../schema/wso2-docs.schema.json', import.meta.url), 'utf8'));
  assert.deepEqual(Object.keys(schema.properties.section.properties).sort(), ['id', 'include', 'label', 'release_tag', 'source_commit', 'version']);
  const shapes = schema.$defs.navItem.oneOf.map((s: { properties: Record<string, unknown> }) => Object.keys(s.properties).sort().join(','));
  assert.deepEqual(shapes, ['label,page', 'category,collapsed,items,overview', 'label,link']);
  // The validator rejects anything else the schema rejects.
  assert.throws(() => parseSection({ id: 'x', version: '1.0.0', release_tag: 'v', extra: 1 }), ConfigError);
  assert.throws(() => parseNav([{ category: 'C', items: [], extra: 1 }]), ConfigError);
});
